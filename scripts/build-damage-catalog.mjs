import {plannerSpell,basicKey} from '../dist/planner-spell.mjs';
import {writeFile} from 'node:fs/promises';
import * as T from '../dist/three.module.js';
import {Duel} from '../dist/duel.mjs';
import {RUNES} from '../dist/combo-design.mjs';
import {DEFAULT_LOADOUT} from '../dist/live-loadout.mjs';
import {advanceMovingWard} from '../dist/moving-ward.mjs';
import {distanceToWard} from '../dist/forces.mjs';
// Deterministic comparison, not a theoretical maximum: no shields, obstacles,
// mastery bonus or wet bonus. The target stays put, even when a spell pushes it.
const samples=[[1.5,0],[2.2,0],[3,0],[5.2,0],[3,.8]];
export function measure(seq,pos=[3,0],options={}){
 const d=new Duel([DEFAULT_LOADOUT,DEFAULT_LOADOUT]),[a,b]=d.actors;
 a.x=a.z=0;b.x=pos[0];b.z=pos[1];a.dir.set(1,0,0);let phase='direct',time=0;const events=[];
 d.hit=(v,damage)=>{if(v===b&&damage>0)events.push({kind:phase,value:damage,time});return true;};
 d.magic.a.collides=()=>false;d.magic.a.clearPath=()=>true;d.magic.a.wallBlocks=()=>false;
 const spell=plannerSpell(seq,options),power=spell.power;
 d.magic.cast(spell,a,new T.Vector3(1,0,0),new T.Vector3(3,0,0));
 const dt=1/30;
 for(let i=0;i<450;i++){time=(i+1)*dt;b.x=pos[0];b.z=pos[1];phase='direct';d.magic.update(dt);phase='dot';d.statuses(dt);phase='direct';
  for(let j=d.wards.length-1;j>=0;j--){const w=d.wards[j];advanceMovingWard(w,dt,{actors:d.actors,collides:()=>false,wards:d.wards});w.life-=dt;w.effectCooldown-=dt;if(w.hp>0&&w.life>0&&w.effectCooldown<=0){w.effectCooldown=.8;if(distanceToWard(b,w)<1){const p=w.spec;if(p.burn||p.slow||p.shock||p.push||p.pull){d.hit(b,p.shock||0);d.payload(b,p,a);}}}if(w.life<=0||w.hp<=0){d.remove(w.m);d.wards.splice(j,1);}}
 }
 const result={power,direct:0,dot:0,total:0,duration:0,groups:[],sample:pos};
 for(const e of events){result[e.kind]+=e.value;result.total+=e.value;result.duration=e.time;let g=result.groups.find(g=>g.kind===e.kind&&Math.abs(g.value-e.value)<1e-7);if(!g){g={kind:e.kind,value:e.value,count:0};result.groups.push(g);}g.count++;}
 d.dispose();return result;
}
const ids=Object.keys(RUNES),seqs=[...ids];for(const a of ids)for(const b of ids){seqs.push(a+b);for(const c of ids)seqs.push(a+b+c);}
const spells={};for(const seq of seqs){let best;for(const pos of samples){const m=measure(seq,pos);if(!best||m.total>best.total)best=m;}spells[seq]=best;}
const basic={};for(const seq of ids)for(const hand of ['left','right'])for(const charged of [false,true]){let best;for(const pos of samples){const m=measure(seq,pos,{hand,charged});if(!best||m.total>best.total)best=m;}basic[basicKey(seq,hand,charged)]=best;}
await writeFile(new URL('../dist/damage-catalog.mjs',import.meta.url),'// Generated by scripts/build-damage-catalog.mjs from the live combat runtime.\nexport const DAMAGE_CATALOG='+JSON.stringify(spells)+';\nexport const BASIC_DAMAGE_CATALOG='+JSON.stringify(basic)+';\n');
console.log('Generated damage comparisons for',seqs.length,'spells');
