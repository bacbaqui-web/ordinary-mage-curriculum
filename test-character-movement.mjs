import assert from 'node:assert/strict';
import {normalizeMovement,readMovement,writeMovement} from './dist/character-movement.mjs';
import {motionStorageKey} from './dist/character-profiles.mjs';
import {BodyFollow,angleDelta} from './dist/body-follow.mjs';
const storage=new Map();globalThis.localStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v)};
assert.deepEqual(normalizeMovement(),{moveSpeed:1,headSpeed:0,chestSpeed:0,pelvisSpeed:0});
writeMovement('ice',{moveSpeed:1.6,headSpeed:720,chestSpeed:180,pelvisSpeed:90});
assert.equal(storage.has(motionStorageKey('ice')),false,'settings must not create an invalid empty motion project');
assert.equal(readMovement('ice').moveSpeed,1.6);assert.equal(readMovement('default').moveSpeed,1);
const project={version:1,actions:[{name:'saved motion'}],movementSettings:readMovement('ice')};
localStorage.setItem(motionStorageKey('ice'),JSON.stringify(project));
writeMovement('ice',{...readMovement('ice'),moveSpeed:1.2});
assert.deepEqual(JSON.parse(localStorage.getItem(motionStorageKey('ice'))).actions,project.actions);
assert.equal(readMovement('ice').moveSpeed,1.2);
const follow=new BodyFollow(readMovement('ice'));follow.update(0,{aim:0});follow.update(.1,{aim:1});
assert.ok(Math.abs(follow.pelvis-Math.PI/20)<1e-9);assert.ok(Math.abs(follow.chest-Math.PI/10)<1e-9);assert.equal(follow.head,1);
const instant=new BodyFollow(normalizeMovement());instant.update(0,{aim:3});instant.update(.1,{aim:-3});
for(const key of ['head','chest','pelvis'])assert.ok(Math.abs(angleDelta(instant[key],-3))<1e-9);
assert.equal(normalizeMovement({moveSpeed:100,headSpeed:-1,chestSpeed:NaN}).moveSpeed,2);
console.log('PASS: per-character movement settings, safe first save, preserved motions, independent rotation rates, immediate turning');

localStorage.setItem(motionStorageKey('earth')+':movement',JSON.stringify({movementSettings:{headSpeed:90,chestSpeed:60,pelvisSpeed:30}}));
localStorage.setItem(motionStorageKey('earth'),JSON.stringify({version:1,actions:[]}));
assert.equal(readMovement('earth').headSpeed,90,'older motion project must not mask saved movement settings');
localStorage.setItem(motionStorageKey('earth')+':movement',JSON.stringify({movementSettings:{headSpeed:120}}));
assert.equal(readMovement('earth').headSpeed,120,'standalone changes invalidate the cache');
